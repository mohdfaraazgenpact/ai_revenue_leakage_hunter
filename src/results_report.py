"""Write the README results block from the latest evaluation artefacts (never edited by hand).

    python -m src.results_report        # called at the end of src.build_all

Every figure is tied to a dataset fingerprint, the generator seed, the git commit and the run time,
so a number in the README can always be traced back to the run that produced it.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from datetime import datetime
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA, REPORTS = ROOT / "data", ROOT / "reports"
README = ROOT / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"
LABELS = {
    "gold": "Answer key (engine-only check, not a detector run)",
    "rule": "Rules baseline (regex)",
    "llm": "AI extraction",
}


def fingerprint() -> str:
    h = hashlib.sha256()
    for rel in ("invoice_lines.csv", "billing_adjustments.csv", "eval/ground_truth.csv"):
        p = DATA / rel
        h.update(p.read_bytes() if p.exists() else b"")
    return h.hexdigest()[:12]


def git_commit() -> str:
    def git(*args):
        return subprocess.run(
            ["git", *args], cwd=ROOT, capture_output=True, text=True
        ).stdout.strip()

    sha = git("rev-parse", "--short", "HEAD") or "unknown"
    dirty = git("status", "--porcelain", "--", "src", "app", "prompts")
    return f"{sha}{' + uncommitted changes' if dirty else ''}"


def _usd(x) -> str:
    return f"${Decimal(str(x)):,.0f}"


def llm_label() -> str:
    """'AI extraction: Claude (claude-sonnet-5-5, Claude Code), prompt extract_terms.v2'."""
    from src.extract.run_extraction import read_provenance

    prov = read_provenance("llm")
    if not prov.get("model"):
        return LABELS["llm"]
    name = {"claude_code": "Claude", "gemini": "Gemini"}.get(
        prov.get("provider"), prov.get("provider")
    )
    via = ", Claude Code" if prov.get("provider") == "claude_code" else ""
    return f"{LABELS['llm']}: {name} ({prov['model']}{via}), prompt {prov.get('prompt_version')}"


def build_block() -> str:
    from src.generate_synthetic_data import SEED

    extraction = {
        e["extractor"]: e
        for e in json.loads((REPORTS / "extraction_summary.json").read_text(encoding="utf-8"))
    }
    evals = {
        p.stem.removeprefix("evaluation_"): json.loads(p.read_text(encoding="utf-8"))
        for p in REPORTS.glob("evaluation_*.json")
    }
    rows = [
        "| Terms source | Field accuracy | Leakage lines found | Precision | $ found vs seeded | "
        "False overbilling | Lines to review | Gate |",
        "|---|---|---|---|---|---|---|---|",
    ]
    labels = {**LABELS, "llm": llm_label()}
    for key in ("gold", "rule", "llm"):
        ev = evals.get(key)
        if ev is None:
            if key == "llm":
                rows.append(f"| {labels[key]} | not run | | | | | | |")
            continue
        acc = "100% (by definition)" if key == "gold" else None
        if acc is None:
            fa = extraction.get(key, {}).get("key_field_accuracy")
            acc = f"{fa:.1%}" if fa is not None else "-"
        gate = "PASS" if not ev["gate_failures"] else "FAIL"
        rows.append(
            f"| {labels[key]} | {acc} | {ev['line_recall']:.1%} ({ev['tp']}/{ev['tp'] + ev['fn']}) | "
            f"{ev['line_precision']:.1%} | {_usd(ev['detected_usd'])} / {_usd(ev['seeded_usd'])} "
            f"({ev['dollar_error_pct']}% error) | {_usd(ev['false_overbilling_usd'])} | "
            f"{ev['review_lines']} | {gate} |"
        )
    any_ev = next(iter(evals.values()), {})
    lines = [
        START,
        "_Generated by `python -m src.results_report` at the end of `src.build_all`. Do not edit by hand._",
        "",
        f"Dataset fingerprint `{fingerprint()}` (generator seed {SEED}) · code `{git_commit()}` · "
        f"generated {datetime.now():%Y-%m-%d %H:%M} · {any_ev.get('lines', '?')} ground-truth invoice lines.",
        "",
        *rows,
        "",
        "Definitions: *Leakage lines found* = line recall on seeded underbilling; *Precision* = share of "
        "flagged underbilling lines that are seeded leakage; *$ found vs seeded* = aggregate underbilling "
        "detected vs seeded; *False overbilling* = overbilling $ on lines with no seeded overbilling; "
        "*Lines to review* = lines the engine refused to price (invalid input, duplicates, currency, "
        "arithmetic, adjustments or undeterminable terms), counted as missed when they hold leakage. "
        "Full definitions and per-scenario tables: `reports/evaluation_<source>.md`.",
        END,
    ]
    return "\n".join(lines)


def update_readme() -> Path:
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"README is missing the {START} ... {END} markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(head + build_block() + tail, encoding="utf-8")
    return README


if __name__ == "__main__":
    print(f"Updated {update_readme()}")
